// The canonical bytes of this package's closed digest inputs, and the State
// mutation digest, kept as the encoder before the direct encoders (014 next9
// ⑤) gave them: generated by that build, ALARMD_REGENERATE_CANONICAL_GOLDEN=1,
// and committed before them. A case without its golden, or a golden without
// its case, is a failure.

// canonicalGoldenTypes is the closed types of this package that reach the
// canonical encoder, each by a value of it.
var canonicalGoldenTypes = map[string]any{
	"state mutation digest payload": stateMutationDigestPayload{},
	"runtime level contract refs":   []RuntimeLevelContractRef{},
	"frozen execution contract ref": FrozenExecutionContractRef{},
	"schedule spec":                 ScheduleSpec{},
	"apply version":                 ApplyVersion{},
	"state key identity":            StateKeyIdentity{},
	"state history points":          []StateHistoryPoint{},
	"plan gap identity":             PlanGapIdentity{},
}

var goldenTexts = []string{"", "plain", "<&>", "ctl\x00\x1f\x7f", "a b ", "bad\xff\xfe", "quote\"back\\", "日本", "x🙂"}

// goldenFill sets value's exported fields from seed, every kind a closed type
// has: a pointer left nil and a slice left nil by turns, others made.
func goldenFill(value reflect.Value, seed int) {
	switch value.Kind() {
	case reflect.String:
		value.SetString(goldenTexts[seed%len(goldenTexts)])
	case reflect.Bool:
		value.SetBool(seed%2 == 1)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		number := int64(seed*7919 - 3)
		if seed%5 == 4 {
			number = math.MinInt64
		}
		for value.OverflowInt(number) {
			number /= 3
		}
		value.SetInt(number)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr:
		number := uint64(seed) * 104729
		if seed%5 == 3 {
			number = math.MaxUint64
		}
		for value.OverflowUint(number) {
			number /= 3
		}
		value.SetUint(number)
	case reflect.Float32, reflect.Float64:
		value.SetFloat(float64(seed) * 1.5e-7)
	case reflect.Pointer:
		if seed%3 != 0 {
			pointer := reflect.New(value.Type().Elem())
			goldenFill(pointer.Elem(), seed+1)
			value.Set(pointer)
		}
	case reflect.Slice:
		if seed%4 == 0 {
			return
		}
		slice := reflect.MakeSlice(value.Type(), seed%3, seed%3)
		for index := 0; index < slice.Len(); index++ {
			goldenFill(slice.Index(index), seed+index+1)
		}
		value.Set(slice)
	case reflect.Array:
		for index := 0; index < value.Len(); index++ {
			goldenFill(value.Index(index), seed+index+1)
		}
	case reflect.Struct:
		for index := 0; index < value.NumField(); index++ {
			if field := value.Field(index); field.CanSet() {
				goldenFill(field, seed+index+1)
			}
		}
	}
}

func canonicalGoldenCases() map[string]func() ([]byte, error) {
	cases := map[string]func() ([]byte, error){}
	for name, sample := range canonicalGoldenTypes {
		sampleType := reflect.TypeOf(sample)
		cases["canonical/"+name+"/zero"] = func() ([]byte, error) {
			return contract.CanonicalJSONV2(reflect.Zero(sampleType).Interface())
		}
		for seed := 1; seed <= 6; seed++ {
			value := reflect.New(sampleType).Elem()
			goldenFill(value, seed)
			filled := value.Interface()
			cases[fmt.Sprintf("canonical/%s/seed %d", name, seed)] = func() ([]byte, error) { return contract.CanonicalJSONV2(filled) }
		}
	}
	// The State mutation digest over payloads of each seed.
	for seed := 1; seed <= 6; seed++ {
		value := reflect.New(reflect.TypeOf(stateMutationDigestPayload{})).Elem()
		goldenFill(value, seed)
		payload := value.Interface().(stateMutationDigestPayload)
		cases[fmt.Sprintf("state mutation digest/seed %d", seed)] = func() ([]byte, error) {
			return contract.CanonicalJSONV2(payload)
		}
		cases[fmt.Sprintf("state mutation canonical digest/seed %d", seed)] = func() ([]byte, error) {
			digest, err := contract.DeriveCanonicalDigestV2("alarmd-golden-v1", payload)
			return []byte(digest), err
		}
	}
	return cases
}

// The canonical bytes of this package's closed digest inputs are the ones
// the encoder before the direct encoders gave (014 next9 ⑤ §5, §6 case 2).
func TestTheCanonicalFormOfTheClosedInputsIsTheGoldenOne(t *testing.T) {
	cases := canonicalGoldenCases()
	got := make(map[string]string, len(cases))
	for name, run := range cases {
		out, err := run()
		if err != nil {
			got[name] = "error: " + err.Error()
			continue
		}
		got[name] = "0x" + hex.EncodeToString(out)
	}
	path := filepath.Join("testdata", "canonical-golden-v1.json")
	if os.Getenv("ALARMD_REGENERATE_CANONICAL_GOLDEN") == "1" {
		raw, err := json.MarshalIndent(got, "", " ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, append(raw, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d golden outcomes to %s", len(got), path)
		return
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("the golden file: %v", err)
	}
	want := map[string]string{}
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(got))
	for name := range got {
		names = append(names, name)
	}
	for name := range want {
		if _, ok := got[name]; !ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	for _, name := range names {
		wanted, kept := want[name]
		outcome, ran := got[name]
		switch {
		case !kept:
			t.Errorf("%s: no golden outcome", name)
		case !ran:
			t.Errorf("%s: a golden outcome with no case", name)
		case outcome != wanted:
			t.Errorf("%s: %s\nwant %s", name, outcome, wanted)
		}
	}
}
