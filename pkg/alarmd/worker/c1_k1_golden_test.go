// c1K1GoldenPath is what Slots read in slices one at a time wrote before
// their slices could be consumed side by side (015 C1), generated by the
// build before it (ALARMD_C1_K1_GOLDEN_OUT names where to write it), and
// generated again where a fix changed what such a Slot writes: a Slot read
// in slices judges no Plan first-seen, its new Plans warm up (first_seen.go).
const c1K1GoldenPath = "testdata/c1-k1-golden.json"

// c1K1Output is what one Execute of a sliced fixture wrote and said, in a
// form two runs of the same build give alike: the slices read, every State
// key's mutation digest, the events and the gap statements in the order
// they went, the completion, and each evaluation line's verdict and the
// series it counts its Plan to have. The events are sorted: how they are
// batched is the windows', and a window's cut follows what the read ahead
// holds when it is cut.
type c1K1Output struct {
	Completed  bool
	Kind       string
	Slices     uint64
	Discarded  uint64
	Reads      []string `json:",omitempty"`
	States     []string
	EventCount int
	Events     []string
	Gaps       []json.RawMessage
	Completion json.RawMessage
	Lines      []string
}

func c1K1Run(t *testing.T, fixture *slicedFixture, request execution.SlotExecutionRequest, reads bool) c1K1Output {
	t.Helper()
	output, _ := c1K1RunResult(t, fixture, request, reads)
	return output
}

// c1K1RunResult is c1K1Run with the Slot's result beside its output.
func c1K1RunResult(t *testing.T, fixture *slicedFixture, request execution.SlotExecutionRequest,
	reads bool,
) (c1K1Output, execution.SlotExecutionResult) {
	t.Helper()
	result, err := fixture.coordinator.Execute(context.Background(), request)
	if err != nil {
		t.Fatalf("Execute() err=%v", err)
	}
	output := c1K1Output{Completed: result.Completed, Kind: string(result.CompletionKind), Slices: result.Usage.InputSlices,
		Discarded: result.Usage.InputSlicesDiscarded, EventCount: fixture.ports.eventCount}
	if reads {
		for _, call := range fixture.source.calls {
			output.Reads = append(output.Reads, call.slice.Digest())
		}
	}
	for key, mutation := range fixture.state.saved {
		output.States = append(output.States, fmt.Sprintf("%s/%s/%s %s", key.Plan.StrategyID, key.StateGeneration,
			key.SeriesIdentityDigest, mutation.MutationDigest))
	}
	sort.Strings(output.States)
	for _, batch := range fixture.ports.eventBatches {
		output.Events = append(output.Events, batch...)
	}
	sort.Strings(output.Events)
	for _, mutation := range fixture.ports.gapMutations {
		encoded, err := json.Marshal(mutation)
		if err != nil {
			t.Fatal(err)
		}
		output.Gaps = append(output.Gaps, encoded)
	}
	completion, err := json.Marshal(fixture.ports.lastProgress.Completion)
	if err != nil {
		t.Fatal(err)
	}
	output.Completion = completion
	for _, observation := range *fixture.observations {
		if observation.Stage != observability.StageEvaluationCompleted {
			continue
		}
		matched := "-"
		if observation.PlanSeriesMatched != nil {
			matched = fmt.Sprint(*observation.PlanSeriesMatched)
		}
		output.Lines = append(output.Lines, fmt.Sprintf("%s/%s/%s %s %s %s", observation.Trace.BusinessID, observation.Trace.StrategyID,
			observation.Trace.DimensionIdentityDigest, observation.Result, observation.ReasonCode, matched))
	}
	sort.Strings(output.Lines)
	return output, result
}

// c1K1Scenarios are the Slots compared: a Slot of a Plan with series and one
// without, read one slice at a time, and read with a slice read ahead; a Slot
// written in windows of three whose second slice answers PARTIAL, its marker
// grown by the slice's head; and a Plan new to its activation, read with
// nothing from before and then with a series its third slice holds written
// before, which warms up either way. Every one of them splits a slice past
// its limit, its number left with no slice.
func c1K1Scenarios(t *testing.T) map[string]c1K1Output {
	t.Helper()
	outputs := map[string]c1K1Output{}
	for name, permits := range map[string]int{"completion-only, one slice at a time": 2, "completion-only, read ahead": 0} {
		fixture := newSlicedFixture(t, slicedHosts(24, 40<<10), sliceableFacts(), 200)
		fixture.queryPermits = permits
		fixture.coordinator = fixture.build(t, worker.Ports{Activation: fixture.ports, State: fixture.state, GapGuard: fixture.ports,
			Events: fixture.ports}, 200)
		plans, requirements, request := withCompletionOnlyPlan(t)
		fixture.source.plans, fixture.source.requirements = plans, requirements
		outputs[name] = c1K1Run(t, fixture, request, permits == 2)
	}
	fixture := newSlicedFixture(t, slicedHosts(24, 40<<10), sliceableFacts(), 3)
	fixture.queryPermits = 2
	fixture.ports.gapMissing = true
	fixture.coordinator = fixture.build(t, worker.Ports{Activation: fixture.ports, State: fixture.state, GapGuard: fixture.ports,
		Events: fixture.ports}, 3)
	fixture.source.completeness = func(_, held int) execution.Completeness {
		if held == 2 {
			return execution.CompletenessPartial
		}
		return execution.CompletenessFull
	}
	outputs["windows of three, a later slice PARTIAL"] = c1K1Run(t, fixture, windowedRequest(), true)
	firstSeen := func(prior []string) *slicedFixture {
		fixture, seen := newSlicedFirstSeenFixtureOf(t, slicedHosts(24, 40<<10), prior, 200)
		fixture.queryPermits = 2
		fixture.coordinator = fixture.build(t, worker.Ports{Activation: seen, State: seen,
			GapGuard: &markerStore{t: t, ports: fixture.ports}, Events: fixture.ports}, 200)
		return fixture
	}
	learn := firstSeen(nil)
	outputs["first-seen, nothing from before"] = c1K1Run(t, learn, windowedRequest(), true)
	var held []string
	for _, slice := range learn.source.landed() {
		if len(slice.delivered) != 0 {
			held = append(held, slice.delivered[0])
		}
	}
	if len(held) < 3 {
		t.Fatalf("fixture: %d slices hold series, want three at least", len(held))
	}
	outputs["first-seen, the third slice finds a series from before"] = c1K1Run(t, firstSeen([]string{held[2]}), windowedRequest(), true)
	return outputs
}

// Read one slice at a time, a Slot writes what it wrote before its slices
// could be consumed side by side: the same slices read, the same State byte
// for byte, the same events and gap statements, the same completion and the
// same evaluation lines (015 C1, every step of appendix B at k = 1).
func TestASlotReadInSlicesWritesWhatItWroteBeforeC1(t *testing.T) {
	outputs := c1K1Scenarios(t)
	if again := c1K1Scenarios(t); !reflect.DeepEqual(outputs, again) {
		for name := range outputs {
			if !reflect.DeepEqual(outputs[name], again[name]) {
				t.Fatalf("%s: two runs of one build differ, the comparison holds something that is not the Slot's: %+v\n%+v",
					name, outputs[name], again[name])
			}
		}
	}
	encoded, err := json.MarshalIndent(outputs, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')
	if out := os.Getenv("ALARMD_C1_K1_GOLDEN_OUT"); out != "" {
		if err := os.WriteFile(out, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s (%d bytes)", out, len(encoded))
		return
	}
	golden, err := os.ReadFile(c1K1GoldenPath)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(encoded, golden) {
		var want map[string]c1K1Output
		if err := json.Unmarshal(golden, &want); err != nil {
			t.Fatal(err)
		}
		for name := range want {
			if !reflect.DeepEqual(outputs[name], want[name]) {
				t.Errorf("%s: the Slot wrote\n%+v\nwhere the build before wrote\n%+v", name, outputs[name], want[name])
			}
		}
		t.Fatal("the Slot's output differs from the build's before C1")
	}
}
