// The canonical bytes, digests and record ids this package gives, kept as the
// encoder before the direct encoders (014 next9 ⑤) gave them: generated by
// that build, ALARMD_REGENERATE_CANONICAL_GOLDEN=1, and committed before them.
// Whatever writes the canonical form from now on is held to these bytes; it
// does not write its own. A case without its golden, or a golden without its
// case, is a failure: the table is the set.

const canonicalGoldenFile = "canonical-golden-v1.json"

// canonicalGoldenOutcome is what one case gives, as kept: its bytes in hex
// after 0x, or its error's text.
func canonicalGoldenOutcome(out []byte, err error) string {
	if err != nil {
		return "error: " + err.Error()
	}
	return "0x" + hex.EncodeToString(out)
}

// checkCanonicalGolden holds cases to the golden file of the package, or
// writes it from them when regenerating.
func checkCanonicalGolden(t *testing.T, cases map[string]func() ([]byte, error)) {
	t.Helper()
	got := make(map[string]string, len(cases))
	for name, run := range cases {
		got[name] = canonicalGoldenOutcome(run())
	}
	path := filepath.Join("testdata", canonicalGoldenFile)
	if os.Getenv("ALARMD_REGENERATE_CANONICAL_GOLDEN") == "1" {
		raw, err := json.MarshalIndent(got, "", " ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, append(raw, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d golden outcomes to %s", len(got), path)
		return
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("the golden file: %v", err)
	}
	want := map[string]string{}
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(got)+len(want))
	for name := range got {
		names = append(names, name)
	}
	for name := range want {
		if _, ok := got[name]; !ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	for _, name := range names {
		wanted, kept := want[name]
		outcome, ran := got[name]
		switch {
		case !kept:
			t.Errorf("%s: no golden outcome; a case is added with its golden from the encoder before", name)
		case !ran:
			t.Errorf("%s: a golden outcome with no case", name)
		case outcome != wanted:
			t.Errorf("%s: %s\nwant %s", name, outcome, wanted)
		}
	}
}

// Closed types with every feature a closed type of this module has, and
// those the standard encoder has besides: tagged, untagged and invalid
// names, omitempty of each kind, skipped and unexported fields, pointers and
// nil pointers, nil and empty slices, arrays, nesting, and numbers of every
// width.
type goldenLeaf struct {
	Text     string  `json:"text"`
	Count    int64   `json:"count,omitempty"`
	Ratio    float64 `json:"ratio"`
	Flag     bool    `json:"flag,omitempty"`
	Small    int8
	Unsigned uint64  `json:"unsigned"`
	Narrow   float32 `json:"narrow,omitempty"`
	Skipped  string  `json:"-"`
	hidden   string
	Dash     string `json:"-,"`
	Odd      string `json:"odd name!"`
	Invalid  string `json:"bad\"name"`
	GoName   uint32 `json:",omitempty"`
}

type goldenNode struct {
	Zebra   string       `json:"zebra"`
	Leaf    goldenLeaf   `json:"leaf"`
	Ptr     *goldenLeaf  `json:"ptr"`
	OptPtr  *goldenLeaf  `json:"opt_ptr,omitempty"`
	List    []goldenLeaf `json:"list"`
	OptList []string     `json:"opt_list,omitempty"`
	Array   [2]uint32    `json:"array"`
	Nested  [][]int      `json:"nested"`
	Alpha   string       `json:"alpha"`
	Wide    uint         `json:"wide"`
	Tiny    uint8        `json:"tiny"`
	Medium  int16        `json:"medium"`
	Int32   int32        `json:"int32,omitempty"`
	OptInts []int64      `json:"opt_ints,omitempty"`
}

var goldenStrings = map[string]string{
	"empty": "", "plain": "plain", "html": "<a href=\"x\">&amp;</a>", "controls": "\x00\x01\x08\x0c\x1f\x7f",
	"escapes": "tab\tnl\ncr\rquote\"back\\slash/", "separators": "a b c", "invalid": "ok\xff\xfe\xc0bad",
	"cjk": "日本語", "emoji": "x🙂y", "escaped separator text": ` `,
}

var goldenFloats = map[string]float64{
	"zero": 0, "negative zero": math.Copysign(0, -1), "e21": 1e21, "under e21": 999999999999999900000, "e-7": 1e-7,
	"e-6": 1e-6, "fraction": 123.456, "max": math.MaxFloat64, "smallest": math.SmallestNonzeroFloat64,
	"negative": -2.5e-8, "integral": 42, "nan": math.NaN(), "inf": math.Inf(1), "negative inf": math.Inf(-1),
}

func goldenLeafOf(text string) goldenLeaf {
	return goldenLeaf{Text: text, Count: -7, Ratio: 0.5, Flag: true, Small: -128, Unsigned: math.MaxUint64, Narrow: 1.25,
		Skipped: "never", hidden: "never", Dash: "dash", Odd: "odd", Invalid: "invalid", GoName: 3}
}

func canonicalGoldenCases() map[string]func() ([]byte, error) {
	cases := map[string]func() ([]byte, error){}
	encode := func(name string, value any) {
		cases["canonical/"+name] = func() ([]byte, error) { return CanonicalJSONV2(value) }
	}
	for name, text := range goldenStrings {
		encode("string/"+name, text)
		leaf := goldenLeafOf(text)
		encode("leaf/text "+name, leaf)
		encode("node/"+name, goldenNode{Zebra: text, Alpha: text, Leaf: leaf, Ptr: &leaf, List: []goldenLeaf{leaf, {}},
			OptList: []string{text, ""}, Array: [2]uint32{0, math.MaxUint32}, Nested: [][]int{{1, -1}, nil, {}},
			Wide: math.MaxUint, Tiny: 255, Medium: math.MinInt16, Int32: math.MinInt32, OptInts: []int64{math.MinInt64, math.MaxInt64}})
	}
	for name, value := range goldenFloats {
		encode("float64/"+name, value)
		encode("float32/"+name, float32(value))
		encode("leaf/ratio "+name, goldenLeaf{Ratio: value, Narrow: float32(value)})
	}
	encode("leaf/zero", goldenLeaf{})
	encode("node/zero", goldenNode{})
	encode("node/empty slices", goldenNode{List: []goldenLeaf{}, OptList: []string{}, Nested: [][]int{}, OptInts: []int64{}})
	encode("pointer/nil", (*goldenLeaf)(nil))
	encode("pointer/leaf", &goldenLeaf{Text: "p"})
	encode("slice/nil", []goldenLeaf(nil))
	encode("slice/empty", []goldenLeaf{})
	encode("slice/strings", []string{"b", "a", " "})
	encode("int64/min", int64(math.MinInt64))
	encode("uint64/max", uint64(math.MaxUint64))
	encode("bool/true", true)
	encode("bool/false", false)
	encode("state compatibility", StateCompatibilityInputV1{StateSchemaVersion: "s", CodecSemanticsVersion: "c",
		SourceTimeSemanticsVersion: "t", HistoryCellSemanticsVersion: "h", IdentitySchemaDigest: sha256Of("identity"),
		EvaluationScope: EvaluationScopeSeries, AggregationInterval: 60, EvaluationInterval: 60})
	encode("level detect", LevelDetectSemanticV1{LevelID: 2, ProjectionDigest: sha256Of("projection"), DetectorSemanticDigest: sha256Of("detector")})
	// Raw JSON: what the single-pass form reads back.
	for name, raw := range map[string]string{"number": "1", "fraction": " 1.50 ", "negative zero": "-0", "exponent": "1E2",
		"true": "true", "null": "null", "string": `"a<b "`, "object": `{"b":1,"a":[2,{"d":null,"c":"é"}]}`,
		"leading zero": "01", "trailing": "1 2", "duplicate": `{"a":1,"a":2}`, "huge": "1e400", "bad surrogate": `"\ud800"`} {
		encode("raw/"+name, json.RawMessage(raw))
	}

	// Digests over the shapes the direct encoders write: a dimension
	// identity, a series' records, record ids.
	identity := func(name, businessID string, fields []DimensionFieldV2) {
		cases["dimension identity/"+name] = func() ([]byte, error) {
			digest, err := DeriveDimensionIdentityDigestV2("tenant", businessID, fields)
			return []byte(digest), err
		}
	}
	values := map[string]string{"string": `"192.0.2.10"`, "escaped": `"a<\"b\\ "`, "number": "1.50", "negative zero": "-0",
		"exponent": "1E2", "true": "true", "false": "false", "null": "null", "spaced": "  5 ", "cjk": `"日本"`}
	for name, value := range values {
		identity("value "+name, "2", []DimensionFieldV2{{Name: "bk_target_ip", Value: json.RawMessage(value)},
			{Name: "zz name", Value: json.RawMessage(`"x"`)}})
	}
	identity("no fields", "2", []DimensionFieldV2{})
	for name, businessID := range map[string]string{"zero": "0", "negative": "-12", "negative zero": "-0", "leading zero": "01",
		"plus": "+1", "empty": "", "letters": "2a", "long": "123456789012345678901234567890"} {
		identity("business "+name, businessID, []DimensionFieldV2{{Name: "a", Value: json.RawMessage(`1`)}})
	}
	identity("object value", "2", []DimensionFieldV2{{Name: "a", Value: json.RawMessage(`{"b":1}`)}})

	fields := []DimensionFieldV2{{Name: "bk_target_ip", Value: json.RawMessage(`"192.0.2.10"`)}, {Name: "device", Value: json.RawMessage(`"eth\u0000"`)}}
	encoded, err := EncodeDimensionIdentityV2("tenant", "2", fields)
	series := encoded.Digest
	records := func(name string, build func() []CanonicalRecordV2) {
		cases["records digest/"+name] = func() ([]byte, error) {
			if err != nil {
				return nil, err
			}
			digest, derr := DeriveSeriesRecordsDigestV2("alarmd-golden-v1", build(), encoded)
			return []byte(digest), derr
		}
	}
	dimensions := map[string]json.RawMessage{"bk_target_ip": json.RawMessage(`"192.0.2.10"`), "device": json.RawMessage(`"eth\u0000"`),
		"日": json.RawMessage(`1`)}
	shared := func(values ...string) []CanonicalRecordV2 {
		out := make([]CanonicalRecordV2, 0, len(values))
		for index, value := range values {
			sourceTime := int64(1_700_000_000 + 60*index)
			id, _ := DeriveRecordIDV2(series, sourceTime)
			out = append(out, CanonicalRecordV2{RecordID: id, SourceTime: sourceTime, BusinessID: "2",
				DimensionIdentity: DimensionIdentityV2{Fields: fields, Digest: series},
				Values:            map[string]json.RawMessage{"_value": json.RawMessage(value)}, Dimensions: dimensions, ReceivedTime: 1_700_000_100})
		}
		return out
	}
	records("shared numbers", func() []CanonicalRecordV2 { return shared("1", "2.50", "-0", "1E3") })
	records("shared literals", func() []CanonicalRecordV2 { return shared("null", "true", `"text "`) })
	records("shared object value", func() []CanonicalRecordV2 { return shared(`{"a":1}`, "1") })
	records("not shared", func() []CanonicalRecordV2 {
		out := shared("1", "2")
		out[1].BusinessID = "3"
		return out
	})
	records("collection time", func() []CanonicalRecordV2 {
		out := shared("1")
		at := int64(5)
		out[0].CollectionTime = &at
		return out
	})
	for _, sourceTime := range []int64{0, 1, 59, 1_700_000_000, math.MaxInt64, -1} {
		cases[fmt.Sprint("record id/", sourceTime)] = func() ([]byte, error) {
			id, err := DeriveRecordIDV2(series, sourceTime)
			return []byte(id), err
		}
	}
	cases["record id/deriver"] = func() ([]byte, error) {
		deriver, err := NewRecordIDDeriverV2(series)
		if err != nil {
			return nil, err
		}
		var out []byte
		for _, sourceTime := range []int64{0, 1, 59, 1_700_000_000, math.MaxInt64} {
			if out, err = deriver.AppendDerive(append(out, ','), sourceTime); err != nil {
				return nil, err
			}
		}
		return out, nil
	}
	cases["record id/bad digest"] = func() ([]byte, error) {
		id, err := DeriveRecordIDV2("ABC", 1)
		return []byte(id), err
	}
	return cases
}

func sha256Of(text string) string {
	digest, err := deriveLengthPrefixedSHA256("golden", "golden-v1", []byte(text))
	if err != nil {
		panic(err)
	}
	return digest
}

// The canonical bytes, digests and record ids are the ones the encoder
// before the direct encoders gave (014 next9 ⑤ §5, §6 case 2).
func TestTheCanonicalFormIsTheGoldenOneTheEncoderBeforeGave(t *testing.T) {
	checkCanonicalGolden(t, canonicalGoldenCases())
}
